import { c as buildLaunchAgentPlist$1, f as resolveLaunchAgentLabel, s as LAUNCH_AGENT_ENV_WRAPPER_SHELL, t as assertNoSystemLaunchDaemonOwnership, u as readLaunchAgentProgramArgumentsFromFile } from "./launchd-system-4KAEGLKr.js";
